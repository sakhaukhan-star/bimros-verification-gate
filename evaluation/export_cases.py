"""
export_cases.py  --  write the ten test cases (T01-T10) to disk

Writes output/<case>_semantic.json and output/<case>_payload.json for every case
generated by run_dsr_evaluation.cases(), so that each case can be run through the
gate from the command line, as in Dissertation Section 4.2:

  python evaluation/export_cases.py
  python src/claude_verification_gate.py --offline --semantic output/T03_semantic.json --payload output/T03_payload.json
"""
import json
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))   # pipeline modules live in src/

from run_dsr_evaluation import cases

OUT = Path(__file__).resolve().parents[1] / "output"   # <repo>/output

if __name__ == "__main__":
    for cid, desc, valid, sem, geo in cases():
        (OUT / f"{cid}_semantic.json").write_text(json.dumps(sem, indent=2))
        (OUT / f"{cid}_payload.json").write_text(json.dumps(geo, indent=2))
        print(f"{cid}  {'valid ' if valid else 'faulty'}  {desc}")
    print(f"written to {OUT}")
